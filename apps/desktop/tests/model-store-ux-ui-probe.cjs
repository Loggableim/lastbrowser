const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const output = path.resolve(__dirname, '../../../output/model-store-ux');
async function main() {
  fs.mkdirSync(output, { recursive: true });
  require('esbuild').buildSync({ entryPoints: [path.join(__dirname,'model-store-ux-fixture.tsx')], bundle: true, platform:'browser', format:'iife', target:'chrome130', loader:{'.woff2':'file'}, outfile:path.join(output,'fixture.js') });
  fs.writeFileSync(path.join(output,'index.html'), '<!doctype html><html lang="de"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="fixture.css"></head><body><div id="root"></div><script src="fixture.js"></script></body></html>');
  const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;
  const child=spawn(process.platform==='win32'?path.join(path.dirname(require.resolve('electron')),'dist','electron.exe'):require('electron'),[__filename,'--child'],{env,cwd:path.resolve(__dirname,'../../..'),windowsHide:true,stdio:'inherit'});
  const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',resolve);});
  assert.equal(code,0);
}
async function child() {
  const { app,BrowserWindow }=require('electron');
  let window;
  try {
    app.setPath('userData',path.join(output,'electron-profile'));
    await app.whenReady();
    window=new BrowserWindow({show:false,width:1280,height:1150,enableLargerThanScreen:true,webPreferences:{contextIsolation:false,nodeIntegration:false}});
    const run=script=>window.webContents.executeJavaScript(script);
    const wait=async(script)=>{const deadline=Date.now()+6000;while(Date.now()<deadline){if(await run(script))return;await new Promise(resolve=>setTimeout(resolve,30));}throw new Error(`DOM condition timed out: ${script}`);};
    const capture=async(name)=>{if(!name.includes('details'))await run('window.scrollTo(0,0)');await new Promise(resolve=>setTimeout(resolve,80));fs.writeFileSync(path.join(output,`${name}.png`),(await window.webContents.capturePage()).toPNG());};
    const click=async(label)=>run(`[...document.querySelectorAll('button')].find(b=>b.textContent.includes(${JSON.stringify(label)}))?.click()`);
    await window.loadFile(path.join(output,'index.html'));window.webContents.setZoomFactor(1);
    await wait("document.querySelector('[data-empty-state=scan_missing]')!==null");
    assert.equal(await run("window.__modelStoreUX.calls.length"),1);
    assert.equal(await run("document.querySelector('.local-model-hardware').textContent.includes('Unbekannt')"),true);
    await capture('01-scan-missing-desktop');
    await click('Hardware scannen');
    await wait("document.querySelector('.local-model-scan-action').textContent.includes('Hardware wird geprüft')");
    await wait("!document.querySelector('.local-model-scan-action button').disabled");
    assert.equal(await run("window.__modelStoreUX.calls.filter(c=>c.payload.request.operation==='scan').length"),1);
    await run("window.__modelStoreUX.scenario('unknown')");
    await wait("document.querySelector('[data-empty-state=compatibility_unknown]')!==null");
    assert.equal(await run("document.querySelector('.local-model-advanced').open"),false);
    await capture('02-unknown-hardware-desktop');
    await click('Alle Modelle ansehen');
    await wait("document.querySelectorAll('.local-model-card').length===3");
    window.setContentSize(1280,1550);await capture('03-browse-unknown-desktop');window.setContentSize(1280,1150);
    await click('Voraussetzungen ansehen');
    await wait("document.activeElement===document.querySelector('.local-model-details')");
    assert.equal(await run("[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Installieren')).disabled"),true);
    window.webContents.sendInputEvent({type:'keyDown',keyCode:'Escape'});
    await wait("document.querySelector('.local-model-details')===null");
    assert.equal(await run("document.activeElement.classList.contains('local-model-card-action')"),true);
    await run("window.__modelStoreUX.scenario('measured')");
    await wait("document.querySelectorAll('.local-model-card').length===1");
    await capture('04-measured-desktop');
    await click('Installation vorbereiten');
    await wait("document.querySelector('.local-model-details')!==null");
    assert.equal(await run("[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Installieren')).disabled"),true);
    await run("[...document.querySelectorAll('.local-model-details input[type=checkbox]')][0].click()");
    assert.equal(await run("[...document.querySelectorAll('button')].find(b=>b.textContent.startsWith('Installieren')).disabled"),false);
    await capture('05-install-consent-details');
    await click('Details schließen');
    await run("window.__modelStoreUX.scenario('unknown')");
    await wait("document.querySelector('[data-empty-state=compatibility_unknown]')!==null");
    window.setContentSize(640,1100);
    await capture('06-unknown-640px');
    assert.equal(await run("document.documentElement.scrollWidth<=window.innerWidth"),true);
    window.setContentSize(1280,1100);window.webContents.setZoomFactor(2);
    await wait("window.innerWidth<=640");
    assert.equal(window.webContents.getZoomFactor(),2);
    await capture('07-unknown-200pct');
    assert.equal(await run("document.documentElement.scrollWidth<=window.innerWidth"),true);
    await click('Alle Modelle ansehen');
    await wait("document.querySelectorAll('.local-model-card').length===3");
    assert.equal(await run("document.documentElement.scrollWidth<=window.innerWidth"),true);
    await capture('08-browse-200pct');
    window.webContents.setZoomFactor(1);window.setContentSize(1280,1150);
    await run("window.__modelStoreUX.scenario('stale')");
    await wait("document.querySelector('.local-model-scan-action').textContent.includes('Hardware-Scan veraltet')");
    await capture('09-stale-hardware-status');
    const operations=await run("window.__modelStoreUX.calls.map(c=>c.payload.request.operation)");
    assert(operations.every(operation=>operation==='view'||operation==='scan'));
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({boundary:'Synthetic fixture rendered by actual Electron DOM; no real hardware, installation, inference or package acceptance',operations,screenshots:9,checks:['missing/unknown states','closed hardware JSON','catalog discovery','unchanged install gates','license consent','focus restoration','640px and 200% no horizontal overflow']},null,2));
    console.log('PASS model-store Electron DOM: 9 screenshots, explicit discovery, install gates, focus, 640px/200% reflow; synthetic fixture only');
    app.exit(0);
  } catch(error) { if(window&&!window.isDestroyed()){fs.writeFileSync(path.join(output,'failure.png'),(await window.webContents.capturePage()).toPNG());console.error(await window.webContents.executeJavaScript('document.body.innerText'));}console.error(error);app.exit(1); }
}
if(process.argv[2]==='--child')void child();else void main().catch(error=>{console.error(error);process.exitCode=1;});
